/*
 * 공휴일 판정 검증 — 실제 달력과 대조.
 *
 * 시간대별(TOU) 요금의 토요일·공휴일 계량 특례가 이 판정에 의존한다. 음력 공휴일은
 * ICU dangi 달력으로 계산하므로, 런타임 ICU가 바뀌면 조용히 틀릴 수 있어 실제 연도
 * 달력을 하드코딩해 고정한다. (일요일·임시공휴일은 제외 — 규정상 별도 처리)
 */

'use strict';

const test = require('node:test');
const assert = require('node:assert');

const H = require('../lib/kr_holidays');

// 실제 공휴일 (법정공휴일 + 대체공휴일, 일요일·임시공휴일 제외)
const CALENDARS = {
  2023: ['01-01', '01-21', '01-22', '01-23', '01-24', '03-01', '05-05', '05-27', '05-29',
    '06-06', '08-15', '09-28', '09-29', '09-30', '10-03', '10-09', '12-25'],
  2024: ['01-01', '02-09', '02-10', '02-11', '02-12', '03-01', '05-05', '05-06', '05-15',
    '06-06', '08-15', '09-16', '09-17', '09-18', '10-03', '10-09', '12-25'],
  2025: ['01-01', '01-28', '01-29', '01-30', '03-01', '03-03', '05-05', '05-06', '06-06',
    '08-15', '10-03', '10-05', '10-06', '10-07', '10-08', '10-09', '12-25'],
  2026: ['01-01', '02-16', '02-17', '02-18', '03-01', '03-02', '05-05', '05-24', '05-25',
    '06-03', '06-06', '08-15', '08-17', '09-24', '09-25', '09-26', '10-03', '10-05',
    '10-09', '12-25'],
};

test('ICU dangi(음력) 달력을 쓸 수 있다', () => {
  assert.strictEqual(H.lunarSupported(), true,
    'dangi 미지원 런타임에서는 음력 공휴일이 평일로 계량됩니다');
});

for (const [year, expected] of Object.entries(CALENDARS)) {
  test(`${year}년 공휴일이 실제 달력과 일치`, () => {
    const got = H.listHolidays(Number(year)).map((k) => k.slice(5));
    assert.deepStrictEqual(got, [...expected].sort());
  });
}

test('대체공휴일 규칙', () => {
  // 삼일절이 일요일(2026-03-01) -> 다음 첫 비공휴일인 3/2 월요일
  assert.ok(H.isPublicHoliday(2026, 3, 2), '2026 삼일절 대체공휴일');
  // 광복절이 토요일(2026-08-15) -> 8/16은 일요일이므로 8/17 월요일
  assert.ok(H.isPublicHoliday(2026, 8, 17), '2026 광복절 대체공휴일');
  assert.ok(!H.isPublicHoliday(2026, 8, 16), '일요일은 표에 넣지 않는다');
  // 어린이날=부처님오신날(2025-05-05)로 겹칠 때 대체공휴일은 하루만
  assert.ok(H.isPublicHoliday(2025, 5, 6), '2025 대체공휴일 5/6');
  assert.ok(!H.isPublicHoliday(2025, 5, 7), '겹쳐도 대체공휴일은 하루만 생긴다');
  // 신정·현충일은 대체공휴일 대상이 아니다
  assert.ok(!H.isPublicHoliday(2023, 1, 2), '신정(2023-01-01 일요일) 대체 없음');
  assert.ok(!H.isPublicHoliday(2026, 6, 8), '현충일(2026-06-06 토요일) 대체 없음');
});

test('설날·추석 연휴는 일요일과 겹칠 때만 대체공휴일', () => {
  // 2026 추석 9/24(목)~9/26(토) — 일요일 없음 -> 대체 없음
  assert.ok(H.isPublicHoliday(2026, 9, 26), '추석 연휴 마지막날(토)');
  assert.ok(!H.isPublicHoliday(2026, 9, 28), '토요일만 걸쳐도 대체공휴일 없음');
  // 2025 추석 10/5(일)~10/7(화) — 일요일 포함 -> 10/8 대체
  assert.ok(H.isPublicHoliday(2025, 10, 8), '2025 추석 대체공휴일');
});

test('평일은 공휴일이 아니다', () => {
  for (const [m, d] of [[2, 10], [4, 15], [7, 15], [9, 10], [11, 20]]) {
    assert.ok(!H.isPublicHoliday(2026, m, d), `2026-${m}-${d}`);
  }
});

test('표에 없는 연도도 예외 없이 계산된다', () => {
  for (const year of [2027, 2028, 2029, 2030, 2035]) {
    const list = H.listHolidays(year);
    assert.ok(list.length >= 15, `${year}년 공휴일이 너무 적습니다: ${list.length}`);
    assert.ok(list.every((k) => /^\d{4}-\d{2}-\d{2}$/.test(k)), '날짜 형식');
    assert.ok(list.every((k) => k.startsWith(`${year}-`)), '해당 연도만 포함');
  }
});
